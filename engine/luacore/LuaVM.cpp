LuaVM::LuaVM()
{
}

LuaVM::~LuaVM()
{
    Release();
}

bool LuaVM::Init(const std::string &strScriptRoot)
{
    XLOG("[INIT] LuaVM initializing with script root: %s", strScriptRoot.c_str());
    m_strScriptRoot = strScriptRoot;

    // Create the Lua state
    m_pL = luaL_newstate();
    if (!m_pL)
    {
        XERR("[LuaVM] Failed to create Lua state");
        return false;
    }

    // Load all standard Lua libraries
    luaL_openlibs(m_pL);

    // Set Lua's module search path to include our script directories.
    std::string pathCmd = "package.path = package.path"
                          " .. ';"
                          + strScriptRoot
                          + "/?.lua'"
                            " .. ';"
                          + strScriptRoot
                          + "/common/?.lua'"
                            " .. ';"
                          + strScriptRoot
                          + "/common/util/?.lua'"
                            " .. ';"
                          + strScriptRoot
                          + "/common/actor/?.lua'"
                            " .. ';"
                          + strScriptRoot
                          + "/actors/?.lua'"
                            " .. ';"
                          + strScriptRoot + "/actors/?/?.lua'";
    luaL_dostring(m_pL, pathCmd.c_str());

    // Initialize the SWIG module (registers all si_* functions)
    if (!InitLuacoreModule())
    {
        XERR("[LuaVM] Failed to initialize luacore module");
        return false;
    }

    // Load the xEngine global module framework.
    // This registers all common modules (Log, Timer, StringExt, Class,
    // ActorBase, ActorMgr, Redis, DB, RPC) into the global xEngine table.
    // Re-executing this file performs a hot-reload of all common modules.
    if (!DoFile(m_strScriptRoot + "/common/include.lua"))
    {
        XERR("[LuaVM] Failed to load common/include.lua");
        return false;
    }

    return true;
}

bool LuaVM::InitLuacoreModule()
{
    if (!m_pL)
    {
        return false;
    }

    // 依次加载各 SWIG 生成的子 core 模块, 各自创建全局表:
    //   luacore          — 框架 + 登录/选角 + 通用 pb + 转发
    //   luacore_friend   — 好友编解码
    //   luacore_room     — 房间编解码
    //   luacore_chat     — 聊天编解码
    //   luacore_battle   — 战斗编解码 + 战斗核心
    //   luacore_spectate — 观战编解码
    //   luacore_config   — 配置热更编解码 + 配置加载
    luaopen_luacore(m_pL);
    luaopen_luacore_friend(m_pL);
    luaopen_luacore_room(m_pL);
    luaopen_luacore_chat(m_pL);
    luaopen_luacore_battle(m_pL);
    luaopen_luacore_spectate(m_pL);
    luaopen_luacore_config(m_pL);

    XLOG("[LuaVM] SWIG 子 core 模块初始化完成 (luacore + 6 个业务子 core)");
    return true;
}

bool LuaVM::DoFile(const std::string &strFilePath)
{
    if (!m_pL)
    {
        XERR("[LuaVM] Lua state not initialized");
        return false;
    }

    if (luaL_dofile(m_pL, strFilePath.c_str()) != LUA_OK)
    {
        XERR("[LuaVM] Error executing '%s': %s", strFilePath.c_str(), lua_tostring(m_pL, -1));
        lua_pop(m_pL, 1); // pop error message
        return false;
    }
    return true;
}

bool LuaVM::DoString(const std::string &strCode)
{
    if (!m_pL)
    {
        XERR("[LuaVM] Lua state not initialized");
        return false;
    }

    if (luaL_dostring(m_pL, strCode.c_str()) != LUA_OK)
    {
        XERR("[LuaVM] Error executing string: %s", lua_tostring(m_pL, -1));
        lua_pop(m_pL, 1); // pop error message
        return false;
    }
    return true;
}

int32 LuaVM::LoadAllActors(const std::string &strPlatform,
                           const std::vector<EActorType> &hostedTypes)
{
    if (!m_pL)
    {
        XERR("[LuaVM] Lua state not initialized");
        return 0;
    }

    // 记录 platform / hostedTypes, 供 HotReload() 复用 (热更时按同类型重跑 init.lua)。
    m_strPlatform = strPlatform;
    m_vecHostedTypes = hostedTypes;

    std::string baseDir = m_strScriptRoot + "/" + strPlatform;
    int32 count = 0;

    // 只加载本进程承载的 Actor 类型对应的目录, 避免非本类型的 init.lua
    // (其中会 hostType + registerPrototype + install) 被误加载。
    for (EActorType actorType : hostedTypes)
    {
        const char *dirName = ActorTypeDirName(actorType);
        if (!dirName)
        {
            XWRN("[LuaVM] Skip unknown actor type=%d", actorType);
            continue;
        }

        std::string initPath = baseDir + "/" + dirName + "/init.lua";
        if (!std::filesystem::exists(initPath))
        {
            XWRN("[LuaVM] init.lua not found for actor type=%d (%s)", actorType, initPath.c_str());
            continue;
        }

        XLOG("[LuaVM] Loading actor type=%d (%s): %s", actorType, dirName, initPath.c_str());
        if (DoFile(initPath))
        {
            count++;
        }
    }

    XLOG("[LuaVM] Loaded %d actor(s) from platform=%s (hosted_types=%zu)", count,
         strPlatform.c_str(), hostedTypes.size());
    return count;
}

bool LuaVM::HotReload()
{
    if (!m_pL)
    {
        XERR("[LuaVM] HotReload: Lua state not initialized");
        return false;
    }

    // 清空 actors.* 的 require 缓存, 使业务脚本 (script/actors/**) 下次 require 时真正重跑。
    // 框架模块 (common.class / common.actor.actor_mgr 等) 不在此列, 其 file-local 注册表
    // (ClassRegistry / protoRegistry / localInstances) 与单例内存态跨重载保留。
    const char *clearScript =
        "for k in pairs(package.loaded) do "
        "  if type(k) == 'string' and k:sub(1, 7) == 'actors.' then "
        "    package.loaded[k] = nil "
        "  end "
        "end";
    if (!DoString(clearScript))
    {
        XERR("[LuaVM] HotReload: failed to clear actors.* module cache");
        return false;
    }

    // 重跑各 actor init.lua。init.lua 里 require("common.include") 命中缓存不重跑框架,
    // 而 require("actors.*") 因上面已清空而重跑; class.lua define() 原地更新旧类表,
    // 既有实例 (metatable.__index 指向同一旧类表) 自动获得新方法。
    int32 count = LoadAllActors(m_strPlatform, m_vecHostedTypes);
    if (count <= 0)
    {
        XWRN("[LuaVM] HotReload: no actor init.lua reloaded (platform=%s hosted=%zu)",
             m_strPlatform.c_str(), m_vecHostedTypes.size());
        return false;
    }

    XLOG("[LuaVM] HotReload OK — reloaded %d actor(s), framework state preserved", count);
    return true;
}

std::vector<std::string> LuaVM::HotReloadFiles(const std::vector<std::pair<std::string, std::string>> &files)
{
    if (!m_pL)
    {
        XERR("[LuaVM] HotReloadFiles: Lua state not initialized");
        return {};
    }
    if (files.empty())
    {
        XWRN("[LuaVM] HotReloadFiles: empty file list");
        return {};
    }

    // 取 xEngine.HotFix.UpdateFilesData 函数 (数据驱动批量入口)。
    lua_getglobal(m_pL, "xEngine");             // [xEngine]
    lua_getfield(m_pL, -1, "HotFix");           // [xEngine, HotFix]
    lua_getfield(m_pL, -1, "UpdateFilesData");  // [xEngine, HotFix, UpdateFilesData]
    if (!lua_isfunction(m_pL, -1))
    {
        lua_pop(m_pL, 3);
        XERR("[LuaVM] HotReloadFiles: xEngine.HotFix.UpdateFilesData not found (hotfix.lua not loaded?)");
        return {};
    }

    // 构造参数表 { {path, source}, ... } (source 用 lua_pushlstring 保二进制安全)。
    lua_createtable(m_pL, (int)files.size(), 0);
    for (size_t i = 0; i < files.size(); ++i)
    {
        lua_createtable(m_pL, 2, 0); // {path, source}
        lua_pushstring(m_pL, files[i].first.c_str());
        lua_rawseti(m_pL, -2, 1);
        lua_pushlstring(m_pL, files[i].second.data(), files[i].second.size());
        lua_rawseti(m_pL, -2, 2);
        lua_rawseti(m_pL, -2, (lua_Integer)(i + 1));
    }

    // 调用 UpdateFilesData(entries), 1 个返回值 (结果表 { [relpath] = boolean })。
    if (lua_pcall(m_pL, 1, 1, 0) != LUA_OK)
    {
        XERR("[LuaVM] HotReloadFiles pcall failed: %s", lua_tostring(m_pL, -1));
        lua_pop(m_pL, 3); // error + HotFix + xEngine
        return {};
    }

    std::vector<std::string> okPaths;
    if (lua_istable(m_pL, -1))
    {
        int32 ok = 0, fail = 0;
        lua_pushnil(m_pL); // 首个 key
        while (lua_next(m_pL, -2) != 0)
        {
            // key = relpath, value = boolean (true=成功或本进程跳过)
            const char *rel = lua_tostring(m_pL, -2);
            bool success = lua_toboolean(m_pL, -1) != 0;
            if (rel)
            {
                if (success)
                {
                    okPaths.push_back(rel);
                    ok++;
                }
                else
                {
                    fail++;
                }
            }
            lua_pop(m_pL, 1); // 弹 value, key 留栈
        }
        XLOG("[LuaVM] HotReloadFiles done: ok=%d fail=%d total=%zu", ok, fail, files.size());
    }
    else
    {
        XWRN("[LuaVM] HotReloadFiles: UpdateFilesData returned non-table");
    }

    lua_pop(m_pL, 3); // result + HotFix + xEngine
    return okPaths;
}

std::pair<bool, std::string> LuaVM::HotReloadPrecheck(
    const std::vector<std::pair<std::string, std::string>> &files)
{
    if (!m_pL)
    {
        XERR("[LuaVM] HotReloadPrecheck: Lua state not initialized");
        return {false, "lua state not initialized"};
    }
    if (files.empty())
    {
        return {true, ""};
    }

    // 取 xEngine.HotFix.PrecheckFilesData 函数 (数据驱动预检查入口)。
    lua_getglobal(m_pL, "xEngine");                    // [xEngine]
    lua_getfield(m_pL, -1, "HotFix");                  // [xEngine, HotFix]
    lua_getfield(m_pL, -1, "PrecheckFilesData");       // [xEngine, HotFix, PrecheckFilesData]
    if (!lua_isfunction(m_pL, -1))
    {
        lua_pop(m_pL, 3);
        XERR("[LuaVM] HotReloadPrecheck: xEngine.HotFix.PrecheckFilesData not found");
        return {false, "PrecheckFilesData not found (hotfix.lua not loaded?)"};
    }

    // 构造参数表 { {path, source}, ... } (source 用 lua_pushlstring 保二进制安全)。
    lua_createtable(m_pL, (int)files.size(), 0);
    for (size_t i = 0; i < files.size(); ++i)
    {
        lua_createtable(m_pL, 2, 0);
        lua_pushstring(m_pL, files[i].first.c_str());
        lua_rawseti(m_pL, -2, 1);
        lua_pushlstring(m_pL, files[i].second.data(), files[i].second.size());
        lua_rawseti(m_pL, -2, 2);
        lua_rawseti(m_pL, -2, (lua_Integer)(i + 1));
    }

    // 调用 PrecheckFilesData(entries), 1 个返回值 { ok=bool, errors={rel=err} }。
    if (lua_pcall(m_pL, 1, 1, 0) != LUA_OK)
    {
        XERR("[LuaVM] HotReloadPrecheck pcall failed: %s", lua_tostring(m_pL, -1));
        lua_pop(m_pL, 3);
        return {false, "PrecheckFilesData pcall failed"};
    }

    bool allOk = true;
    std::string summary;
    if (lua_istable(m_pL, -1))
    {
        lua_getfield(m_pL, -1, "ok");   // [..., result, ok]
        if (lua_isboolean(m_pL, -1))
        {
            allOk = lua_toboolean(m_pL, -1) != 0;
        }
        lua_pop(m_pL, 1); // ok

        lua_getfield(m_pL, -1, "errors"); // [..., result, errors]
        if (lua_istable(m_pL, -1))
        {
            lua_pushnil(m_pL);
            while (lua_next(m_pL, -2) != 0)
            {
                // key = relpath, value = errmsg
                const char *rel = lua_tostring(m_pL, -2);
                const char *err = lua_tostring(m_pL, -1);
                if (rel && err)
                {
                    if (!summary.empty())
                    {
                        summary += "\n";
                    }
                    summary += std::string(rel) + ": " + err;
                }
                lua_pop(m_pL, 1);
            }
        }
        lua_pop(m_pL, 1); // errors
    }
    else
    {
        XWRN("[LuaVM] HotReloadPrecheck: PrecheckFilesData returned non-table");
        allOk = false;
        summary = "precheck returned non-table";
    }

    lua_pop(m_pL, 3); // result + HotFix + xEngine
    XLOG("[LuaVM] HotReloadPrecheck done: ok=%d files=%zu%s", allOk ? 1 : 0, files.size(),
         summary.empty() ? "" : "");
    return {allOk, summary};
}

void LuaVM::Release()
{
    if (m_pL)
    {
        lua_close(m_pL);
        m_pL = nullptr;
        XLOG("[LuaVM] Lua state released");
    }
}
