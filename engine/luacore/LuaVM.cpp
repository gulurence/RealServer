// Forward declaration of SWIG's module init function.
// Generated by SWIG in luacore_wrap.cxx, this function
// creates the global "luacore" table with all si_* functions.
extern "C" int32 luaopen_luacore(lua_State *L);
extern "C" int32 luaopen_luacore_friend(lua_State *L);
extern "C" int32 luaopen_luacore_room(lua_State *L);
extern "C" int32 luaopen_luacore_chat(lua_State *L);
extern "C" int32 luaopen_luacore_battle(lua_State *L);
extern "C" int32 luaopen_luacore_spectate(lua_State *L);
extern "C" int32 luaopen_luacore_config(lua_State *L);

